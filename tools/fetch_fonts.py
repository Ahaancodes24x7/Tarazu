"""Download the web fonts once and serve them locally, so the app needs no network.

Keeps only the scripts Tarazu uses (Latin, Devanagari, Gurmukhi) and writes
frontend/assets/fonts/*.woff2 plus frontend/assets/css/fonts.css.
Run: python tools/fetch_fonts.py
"""
import hashlib
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "assets" / "fonts"
CSS = ROOT / "frontend" / "assets" / "css" / "fonts.css"
FAMILIES = (
    "family=IBM+Plex+Mono:wght@400;500"
    "&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;0,700;1,400"
    "&family=IBM+Plex+Sans+Devanagari:wght@400;500;600"
    "&family=Newsreader:ital,opsz,wght@0,6..72,300..700;1,6..72,400"
    "&family=Noto+Sans+Gurmukhi:wght@400;500;600"
    "&family=Noto+Sans+Devanagari:wght@400;600"
    "&family=Kalam:wght@300;400;700"
)
KEEP = {"latin", "latin-ext", "devanagari", "gurmukhi"}
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"


def get(url: str) -> bytes:
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=60).read()


def main() -> None:
    css = get(f"https://fonts.googleapis.com/css2?{FAMILIES}&display=swap").decode()
    OUT.mkdir(parents=True, exist_ok=True)
    blocks = re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, re.S)
    kept, total = [], 0
    for subset, block in blocks:
        if subset not in KEEP:
            continue
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        data = get(url)
        name = hashlib.sha1(url.encode()).hexdigest()[:12] + ".woff2"
        (OUT / name).write_bytes(data)
        total += len(data)
        kept.append(f"/* {subset} */\n" + block.replace(url, f"../fonts/{name}"))
    CSS.write_text("/* Generated by tools/fetch_fonts.py: local copies of the web fonts. */\n" + "\n".join(kept) + "\n",
                   encoding="utf-8")
    print(f"{len(kept)} font files, {total / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
